-- 1. EXTENSIONES Y ESQUEMAS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE SCHEMA IF NOT EXISTS private;

-- 2. TABLA PROFILES (Usuarios y Empleados del Minimarket)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY,
  nombre TEXT NOT NULL,
  rol TEXT NOT NULL DEFAULT 'employee' CHECK (rol IN ('admin', 'employee')),
  email TEXT,
  avatar_url TEXT,
  activo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Función get_user_role()
CREATE OR REPLACE FUNCTION private.get_user_role()
RETURNS text
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO ''
AS $$
  SELECT p.rol FROM public.profiles p WHERE p.id = (SELECT auth.uid())
$$;

-- Trigger para auto-crear perfil cuando se registra un usuario en auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, nombre, rol, email)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'nombre', NEW.raw_user_meta_data->>'name', NEW.email),
    COALESCE(NEW.raw_app_meta_data->>'role', NEW.raw_user_meta_data->>'rol', 'employee'),
    NEW.email
  )
  ON CONFLICT (id) DO UPDATE SET
    nombre = EXCLUDED.nombre,
    email = EXCLUDED.email;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 3. TABLA CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  orden INTEGER NOT NULL DEFAULT 1,
  activa BOOLEAN NOT NULL DEFAULT true
);

-- 4. TABLA PRODUCTOS (Inventario de Minimarket)
CREATE TABLE IF NOT EXISTS public.productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
  nombre TEXT NOT NULL,
  descripcion TEXT,
  imagen_url TEXT,
  precio_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  costo_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  stock INTEGER NOT NULL DEFAULT 0,
  stock_minimo INTEGER NOT NULL DEFAULT 5,
  codigo_barras TEXT,
  unidad TEXT NOT NULL DEFAULT 'und',
  disponible BOOLEAN NOT NULL DEFAULT true,
  orden INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. TABLA CLIENTES (Clientes y Créditos)
CREATE TABLE IF NOT EXISTS public.clientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  cedula TEXT,
  telefono TEXT,
  email TEXT,
  direccion TEXT,
  notas TEXT,
  tiene_credito BOOLEAN NOT NULL DEFAULT false,
  limite_credito_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  saldo_credito_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  activo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. TABLA PEDIDOS / VENTAS
CREATE TABLE IF NOT EXISTS public.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registrado_por UUID NOT NULL REFERENCES public.profiles(id),
  id_cliente BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
  tipo TEXT NOT NULL DEFAULT 'directo',
  estado_pago TEXT NOT NULL DEFAULT 'pagado' CHECK (estado_pago IN ('pagado', 'credito', 'anulado')),
  subtotal_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  total_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  total_ves NUMERIC(12,2),
  tasa_cambio_aplicada NUMERIC(10,2),
  es_credito BOOLEAN NOT NULL DEFAULT false,
  nota TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. TABLA DETALLES_PEDIDO (Items de cada venta)
CREATE TABLE IF NOT EXISTS public.detalles_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido BIGINT NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  id_producto BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL DEFAULT 1,
  precio_congelado_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  subtotal_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. TABLA PAGOS (Detalle de pagos recibidos)
CREATE TABLE IF NOT EXISTS public.pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido BIGINT NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  monto_usd NUMERIC(10,2) NOT NULL DEFAULT 0,
  monto_ves NUMERIC(12,2),
  metodo_pago TEXT NOT NULL,
  moneda TEXT NOT NULL DEFAULT 'USD',
  referencia TEXT,
  tasa_aplicada NUMERIC(10,2),
  registrado_por UUID NOT NULL REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. TABLA ARQUEOS (Arqueo físico de inventario)
CREATE TABLE IF NOT EXISTS public.arqueos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  realizado_por UUID NOT NULL REFERENCES public.profiles(id),
  estado TEXT NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto', 'cerrado', 'revisado')),
  notas TEXT,
  revisado_por UUID REFERENCES public.profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  closed_at TIMESTAMPTZ
);

-- 10. TABLA DETALLES_ARQUEO (Conteo físico de productos)
CREATE TABLE IF NOT EXISTS public.detalles_arqueo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_arqueo BIGINT NOT NULL REFERENCES public.arqueos(id) ON DELETE CASCADE,
  id_producto BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  stock_sistema INTEGER NOT NULL DEFAULT 0,
  cantidad_contada INTEGER NOT NULL DEFAULT 0,
  diferencia INTEGER DEFAULT 0,
  notas TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 11. TABLA TASA_CAMBIO (Tasa de Cambio BCV / Manual)
CREATE TABLE IF NOT EXISTS public.tasa_cambio (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tasa NUMERIC(10,2) NOT NULL,
  fecha_vigencia TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  registrado_por UUID REFERENCES public.profiles(id),
  fuente TEXT NOT NULL DEFAULT 'bcv',
  es_activa BOOLEAN NOT NULL DEFAULT true,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

